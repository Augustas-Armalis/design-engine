// Halyard routes drawn properly (drawing-method step 3): one contour per mark, outer corners continuous (G2), inner
// corners sharp, one stroke ratio (stem : bar = 1.6), one angle system (the hoist tilt), one terminal rule.
// Writes work/halyard/brand/finalists.mjs (for `node tools/logo.mjs present`) and one SVG per route for the QA tools.
const fs = require('fs')
const K = require('../../../tools/logo_drawkit.cjs')
const { Path, Point } = K
const P = (x, y) => new Point(x, y)
const poly = (pts) => new Path({ segments: pts.map(([x, y]) => P(x, y)), closed: true })

const S = 200, BAR = 125, X = [140, 660], TOP = 100, BOT = 900
const rise = (dx, tilt) => dx * Math.tan((tilt * Math.PI) / 180)

/** Hoist H: the bar climbs the right stem; stem tops (and optionally feet) are cut parallel to the bar */
function hoistH(tilt = 14, feet = false, barY = 470) {
  const r = rise(S, tilt), br = rise(X[1] - (X[0] + S), tilt)
  const L = X[0], Lr = X[0] + S, R = X[1], Rr = X[1] + S
  const pts = [
    [L, BOT], [L, TOP + r], [Lr, TOP], [Lr, barY], [R, barY - br], [R, TOP + r], [Rr, TOP],
    [Rr, feet ? BOT - r : BOT], [R, BOT], [R, barY - br + BAR], [Lr, barY + BAR], [Lr, feet ? BOT - r : BOT],
  ]
  if (feet) { pts[11] = [Lr, BOT - r]; pts[0] = [L, BOT] }
  return K.filletOuter(poly(pts), 34, { mode: 'continuous', spread: 1.6 })
}

/** Sail H: left stem is the mast, the bar climbs, the right stem is a sail with a full leech */
function sailH(tilt = 14, full = 0.22) {
  const r = rise(S, tilt), br = rise(X[1] - (X[0] + S), tilt)
  const mastBar = K.filletOuter(poly([[X[0], BOT], [X[0], TOP + r], [X[0] + S, TOP], [X[0] + S, 470], [X[1] + 20, 470 - br], [X[1] + 20, 470 - br + BAR], [X[0] + S, 470 + BAR], [X[0] + S, BOT]]), 34, { mode: 'continuous' })
  const head = P(X[1], TOP), clew = P(X[1] + S + 120, BOT - 60), tack = P(X[1], BOT)
  const s = new Path({ closed: true }); s.moveTo(tack); s.lineTo(head)
  const d = clew.subtract(head), n = new Point(d.y, -d.x).normalize(d.length * full)
  s.cubicCurveTo(head.add(d.multiply(0.3)).add(n), head.add(d.multiply(0.75)).add(n.multiply(0.75)), clew)
  s.cubicCurveTo(clew.add(P(-60, 50)), tack.add(P(80, 0)), tack)
  return mastBar.unite(s)
}

const routes = {
  'A · Hoist H': { idea: 'An H whose bar climbs the right stem at 14 degrees, thinner than the stems (1 : 1.6); the stem tops are cut on the same angle, so the whole letter leans into the hoist.', item: hoistH(14) },
  'A2 · Hoist H, steeper': { idea: 'The same H at 20 degrees: more lift, the bar meets the right stem a third higher.', item: hoistH(20) },
  'B · Hoist H, cut feet': { idea: 'Every terminal cut on the hoist angle, tops and feet: the letter reads as moving, like type set in motion.', item: hoistH(14, true) },
  'C · Sail H': { idea: 'The left stem is the mast, the bar climbs, and the right stem is a sail with a full leech: the letter and the boat in one shape.', item: sailH(14, 0.22) },
}
const marks = {}
for (const [k, v] of Object.entries(routes)) {
  const inner = K.toMarkSvg(K.addExtrema(v.item))
  marks[k] = { idea: v.idea, svg: inner }
  const slug = k.split('·')[0].trim().toLowerCase()
  fs.writeFileSync(`${__dirname}/route-${slug}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" fill="#000">${inner}</svg>`)
}
fs.writeFileSync(`${__dirname}/finalists.mjs`, `// generated by draw.cjs\nexport default ${JSON.stringify(marks, null, 1)}\n`)
console.log('routes:', Object.keys(marks).join(', '))
